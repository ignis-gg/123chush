 * Idempotent content rewrite: reposition the whole site from "we handle/
 * file/represent" language to pure informational-consultation framing, for
 * Google Ads compliance (Ads treats "we file/represent/prepare packages"
 * copy as an active legal service, not an informational one — see
 * docs/known-issues.md and docs/next-session.md, session 2026-09-14).
 *
 * Two kinds of changes:
 *  1. A big ordered list of string-pair replacements (`$pairs`), applied
 *     recursively across post_title/content/excerpt + all postmeta of
 *     every `service` post, plus the front page (7) and About page (21),
 *     via the same rr()/sync_post_fields()/sync_post_meta() pattern as
 *     2026-09-12-sync-docx-edits.php. Purely additive/idempotent — once a
 *     phrase is gone, the replace is a no-op on re-run.
 *  2. Structural ACF array overrides for a handful of fields where simple
 *     string substitution can't fix the grammar/meaning (post 143's
 *     compare_rows/testimonials/advantages_steps/process_steps/faq_items,
 *     which explicitly claimed courtroom representation).
 *  3. Taxonomy term descriptions (service_category) and site-wide options
 *     (tagline, CTA form lead, legalization disclaimer) set to their final
 *     values directly (idempotent: no-op if already equal).
 *
 * Run: wp eval-file bin/migrations/2026-09-14-informational-positioning.php
 * Safe to re-run.
 */

function ip_rr( $v, $pairs ) {
	if ( is_string( $v ) ) {
		foreach ( $pairs as $old => $new ) {
			$v = str_replace( $old, $new, $v );
		}
		return $v;
	}
	if ( is_array( $v ) ) {
		foreach ( $v as $k => $vv ) {
			$v[ $k ] = ip_rr( $vv, $pairs );
		}
		return $v;
	}
	return $v;
}

function ip_sync_post( $post_id, $pairs ) {
	$post = get_post( $post_id );
	if ( ! $post ) {
		echo "SKIP: post $post_id not found\n";
		return;
	}
	$updates = array();
	foreach ( array( 'post_title', 'post_content', 'post_excerpt' ) as $f ) {
		$new = ip_rr( $post->$f, $pairs );
		if ( $new !== $post->$f ) {
			$updates[ $f ] = $new;
		}
	}
	if ( $updates ) {
		$updates['ID'] = $post_id;
		wp_update_post( $updates );
		echo "Updated post $post_id fields: " . implode( ',', array_keys( $updates ) ) . "\n";
	}
	$meta = get_post_meta( $post_id );
	foreach ( $meta as $key => $vals ) {
		if ( 0 === strpos( $key, '_' ) ) {
			continue; // ACF's internal field-key refs, never touch.
		}
		foreach ( $vals as $raw ) {
			$val     = maybe_unserialize( $raw );
			$new_val = ip_rr( $val, $pairs );
			if ( $new_val !== $val ) {
				update_post_meta( $post_id, $key, $new_val, $val );
				echo "Updated post $post_id meta '$key'\n";
			}
		}
	}
}

