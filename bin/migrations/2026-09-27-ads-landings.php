/**
 * Returns the attachment ID for a bundled photo, importing it once.
 */
$koval_photo = function ( $file, $alt ) use ( $koval_assets_dir ) {
	$existing = get_posts( array(
		'post_type'      => 'attachment',
		'post_status'    => 'inherit',
		'meta_key'       => '_koval_ads_asset',
		'meta_value'     => $file,
		'fields'         => 'ids',
		'posts_per_page' => 1,
	) );
	if ( $existing ) {
		return (int) $existing[0];
	}
	$path = $koval_assets_dir . '/' . $file;
	if ( ! file_exists( $path ) ) {
		echo "MISSING PHOTO: {$path}\n";
		return 0;
	}
	$tmp = wp_tempnam( $file );
	copy( $path, $tmp );
	$id = media_handle_sideload( array( 'name' => $file, 'tmp_name' => $tmp ), 0, $alt );
	if ( is_wp_error( $id ) ) {
		echo 'PHOTO ERROR ' . $file . ': ' . $id->get_error_message() . "\n";
		@unlink( $tmp );
		return 0;
	}
	update_post_meta( $id, '_koval_ads_asset', $file );
	update_post_meta( $id, '_wp_attachment_image_alt', $alt );
	echo "PHOTO IMPORTED: {$file} -> {$id}\n";
	return (int) $id;
};

$koval_by_slug = function ( $slug, $type = 'service' ) {
	$p = get_page_by_path( $slug, OBJECT, $type );
	return $p ? (int) $p->ID : 0;
};

$koval_blog_by_title = function ( $title ) {
	$p = get_posts( array( 'post_type' => 'post', 'post_status' => 'publish', 'title' => $title, 'posts_per_page' => 1, 'fields' => 'ids' ) );
	return $p ? (int) $p[0] : 0;
};

