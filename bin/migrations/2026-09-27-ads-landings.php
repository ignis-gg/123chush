// Pass 1: create/update every post (so related links between the new
// pages resolve in pass 2).
$ids = array();
foreach ( $pages as $page ) {
	$post_id = $koval_by_slug( $page['slug'] );
	$data    = array(
		'post_type'    => 'service',
		'post_status'  => 'publish',
		'post_title'   => $page['title'],
		'post_name'    => $page['slug'],
		'post_excerpt' => $page['fields']['ads_lead'],
	);
	if ( $post_id ) {
		$data['ID'] = $post_id;
		wp_update_post( $data );
		echo "UPDATED: {$page['slug']} ({$post_id})\n";
	} else {
		$data['post_content'] = '';
		$post_id              = wp_insert_post( $data, true );
		if ( is_wp_error( $post_id ) ) {
			echo 'ERROR ' . $page['slug'] . ': ' . $post_id->get_error_message() . "\n";
			continue;
		}
		echo "CREATED: {$page['slug']} ({$post_id})\n";
	}
	$ids[ $page['slug'] ] = (int) $post_id;
}

// Pass 2: fields.
foreach ( $pages as $page ) {
	if ( empty( $ids[ $page['slug'] ] ) ) {
		continue;
	}
	$post_id = $ids[ $page['slug'] ];

	wp_set_object_terms( $post_id, $page['category'], 'service_category' );

	update_field( 'ads_landing', 1, $post_id );
	foreach ( $page['fields'] as $key => $value ) {
		update_field( $key, $value, $post_id );
	}
	update_field( 'ads_hero_image', $koval_photo( $page['hero'][0], $page['hero'][1] ), $post_id );
	update_field( 'ads_steps_image', $photo_steps, $post_id );

	$related = array();
	foreach ( $page['related'] as $ref ) {
		$rid = 0 === strpos( $ref, 'blog:' ) ? $koval_blog_by_title( substr( $ref, 5 ) ) : ( $ids[ $ref ] ?? $koval_by_slug( $ref ) );
		if ( $rid ) {
			$related[] = $rid;
		} else {
			echo "  related not found: {$ref}\n";
		}
	}
	update_field( 'ads_related', $related, $post_id );

	update_field( 'catalog_title', $page['catalog'][0], $post_id );
	update_field( 'catalog_short_description', $page['catalog'][1], $post_id );
	update_post_meta( $post_id, 'rank_math_title', $page['seo'][0] );
	update_post_meta( $post_id, 'rank_math_description', $page['seo'][1] );

	echo "  fields ok: {$page['slug']} -> " . get_permalink( $post_id ) . "\n";
}
